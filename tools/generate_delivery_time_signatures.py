"""Emit linked native offer-creation templates. No version/hash gate at runtime."""
import sys
from compare_executables import Image, ROOT, md, CS_GRP_JUMP, CS_GRP_CALL
from capstone.x86 import X86_OP_IMM, X86_OP_MEM, X86_REG_RIP

FUNCTIONS = [
    ('freight_factory',0xa34db0), ('owned_factory',0xa35310), ('offer_constructor',0xa34ff0),
    ('freight_window',0xa35200), ('owned_window',0xa354d0),
]



def collect(image, start):
    pending, found = [start], {}
    while pending:
        pc = pending.pop()
        if pc in found: continue
        if not start <= pc < start + 0x10000: raise ValueError(f'Unexpected flow {start:x} -> {pc:x}')
        for i in md.disasm(bytes(image.data[pc:pc+0x4000]), pc):
            if i.address in found: break
            found[i.address] = i
            if i.group(CS_GRP_JUMP):
                if i.operands[0].type == X86_OP_IMM: pending.append(i.operands[0].imm)
                if i.mnemonic == 'jmp': break
            if i.mnemonic in ('ret', 'int3'): break
    return [i for _,i in sorted(found.items())]


def generate():
    image = Image(ROOT/'diagnostics/executables/ats-public-1.62.2.2/amtrucks.exe')
    entries = {rva:n for n,(_,rva) in enumerate(FUNCTIONS)}
    symbols, exported = {}, {}
    output = ['// Generated by tools/generate_delivery_time_signatures.py.',
              '// Full linked instruction/flow checks before hooks. No exact EXE addresses at runtime.']
    reference_sites = {0xa35015:'freight_vtable',0xa35347:'owned_vtable'}
    for name, start in FUNCTIONS:
        assert start in image.functions, (name,hex(start),'not a native function entry')
        code = collect(image,start)
        positions = {i.address:n for n,i in enumerate(code)}
        output.append(f'static constexpr Instruction {name}_instructions[] = {{')
        for i in code:
            data = bytearray(i.bytes)
            offset = width = kind = 0
            target = callee = symbol = -1
            next_node = positions.get(i.address+i.size,-1)
            if any(o.type==X86_OP_MEM and o.mem.base==X86_REG_RIP for o in i.operands):
                offset,width,kind = i.disp_offset,i.disp_size,1
                symbol = symbols.setdefault(i.address+i.size+i.disp,len(symbols))
                if i.address in reference_sites: exported[reference_sites[i.address]]=symbol
            if (i.group(CS_GRP_CALL) or i.group(CS_GRP_JUMP)) and i.operands[0].type==X86_OP_IMM:
                offset,width,kind = i.imm_offset,i.imm_size,2
                callee = entries.get(i.operands[0].imm,-1)
                if i.group(CS_GRP_JUMP) and i.operands[0].imm in positions:
                    kind,target=3,positions[i.operands[0].imm]
                else: symbol=symbols.setdefault(i.operands[0].imm,len(symbols))
            if i.mnemonic in ('jmp','ret','int3'): next_node=-1
            if width: data[offset:offset+width]=bytes(width)
            values=','.join(f'0x{b:02x}' for b in data)
            output.append(f'    {{{{{values}}}, {i.size},{offset},{width},{kind},{next_node},{target},{callee},{symbol}}},')
        output.append('};')
    output.append('static constexpr Signature signatures[] = {')
    for name,_ in FUNCTIONS: output.append(f'    {{"{name}",{name}_instructions,std::size({name}_instructions)}},')
    output += ['};', f'static constexpr unsigned symbol_count={len(symbols)};']
    for n,(name,_) in enumerate(FUNCTIONS): output.append(f'static constexpr unsigned {name}_index={n};')
    assert len(exported)==2
    for name,symbol in exported.items(): output.append(f'static constexpr unsigned {name}_symbol={symbol};')
    return '\n'.join(output)+'\n'


if __name__=='__main__':
    path=ROOT/'src/delivery_time_signatures_162.inc'
    result=generate()
    if '--check' in sys.argv: assert path.read_text()==result, 'Creation signatures are stale'
    else: path.write_text(result)
    print(f'{path.name}: {len(result)} characters')
