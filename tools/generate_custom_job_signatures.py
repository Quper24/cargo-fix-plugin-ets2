"""Generate code/flow guards for the 1.62 session token-pool reader."""
import sys
from compare_executables import Image, ROOT, CS_GRP_JUMP, CS_GRP_CALL
from generate_game_signatures import collect
from capstone.x86 import X86_OP_IMM, X86_OP_MEM, X86_REG_RIP


def generate(names=False):
    source = 'ets2-public-1.62.3.3' if names else 'ets2-public-1.62.1.0'
    image = Image(ROOT / f'diagnostics/executables/{source}/eurotrucks2.exe')
    functions = [('localize', 0x15567c0)] if names else [('company_location', 0x7bcbf0), ('unit_token', 0x13ea40)]
    entries = {rva: n for n, (_, rva) in enumerate(functions)}
    symbols = {}
    output = ['// Generated by tools/generate_custom_job_signatures.py.',
              '// Complete instruction/flow templates; only PC-relative addresses vary.']
    pools = None
    for name, start in functions:
        instructions = collect(image, start)
        positions = {i.address: n for n, i in enumerate(instructions)}
        output.append(f'static constexpr Instruction {name}_instructions[] = {{')
        for i in instructions:
            code = bytearray(i.bytes)
            offset = width = kind = 0
            target = callee = symbol = -1
            next_node = positions.get(i.address + i.size, -1)
            if any(o.type == X86_OP_MEM and o.mem.base == X86_REG_RIP for o in i.operands):
                offset, width, kind = i.disp_offset, i.disp_size, 1
                address = i.address + i.size + i.disp
                symbol = symbols.setdefault(address, len(symbols))
                if name == 'unit_token' and i.mnemonic == 'lea' and i.op_str.startswith('rdx, [rip +'):
                    assert pools is None
                    pools = symbol
                if names and i.address == 0x1556818:
                    assert i.mnemonic == 'lea' and address == 0x22980e0
                    pools = symbol
            if (i.group(CS_GRP_CALL) or i.group(CS_GRP_JUMP)) and i.operands[0].type == X86_OP_IMM:
                offset, width, kind = i.imm_offset, i.imm_size, 2
                callee = entries.get(i.operands[0].imm, -1)
                if i.group(CS_GRP_JUMP) and i.operands[0].imm in positions:
                    kind, target = 3, positions[i.operands[0].imm]
                else:
                    symbol = symbols.setdefault(i.operands[0].imm, len(symbols))
                if i.mnemonic == 'jmp': next_node = -1
            if i.mnemonic in ('ret', 'int3'): next_node = -1
            if width: code[offset:offset+width] = bytes(width)
            values = ','.join(f'0x{b:02x}' for b in code)
            output.append(f'    {{{{{values}}}, {i.size},{offset},{width},{kind},{next_node},{target},{callee},{symbol}}},')
        output.append('};')
    output.append('static constexpr Signature signatures[] = {')
    for name, _ in functions:
        output.append(f'    {{"{name}", {name}_instructions, std::size({name}_instructions)}},')
    assert pools is not None
    output += ['};', f'static constexpr unsigned symbol_count = {len(symbols)};',
               f'static constexpr unsigned {"buffer_vtable_symbol" if names else "pools_symbol"} = {pools};']
    return '\n'.join(output) + '\n'


if __name__ == '__main__':
    for names in (False, True):
        path = ROOT / ('src/custom_name_signatures_162.inc' if names else 'src/custom_job_signatures_162.inc')
        result = generate(names)
        if '--check' in sys.argv:
            assert path.read_text() == result, 'Catalog signatures are stale'
        else:
            path.write_text(result)
        print(f'{path.name}: {len(result)} characters')
