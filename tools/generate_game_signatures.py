"""Generate instruction/flow templates; Capstone is used only by this offline tool."""
import sys
from compare_executables import Image, ROOT, md, CS_GRP_JUMP, CS_GRP_CALL
from capstone.x86 import X86_OP_IMM, X86_OP_MEM, X86_REG_RIP

LAYOUTS = {
    '161': dict(source='reference-1.61.1.9-mapped.bin', mapped=True,
                functions=[('clear_vector', 0x116510), ('fill', 0x7cd0f0), ('refill', 0x7cddf0),
                           ('generator', 0x7cfba0), ('clear', 0x7d0ce0), ('schedule', 0x81cec0),
                           ('stock_refresh', 0x4a0060)],
                blocks=[('economy_source', 0x3f4141), ('economy_action', 0x49c080),
                        ('economy_confirmation', 0x419470)], budget_branch=0x265, budget_stack=0x70),
    '162': dict(source='public_beta-1.62.0.10/eurotrucks2.exe', mapped=False,
                functions=[('clear_vector', 0x1189f0), ('fill', 0x7b7890), ('refill', 0x7b8590),
                           ('generator', 0x7ba390), ('clear', 0x7bb500), ('schedule', 0x808860),
                           ('stock_refresh', 0x4aa3f0)],
                blocks=[('economy_source', 0x3fce21), ('economy_action', 0x4a5e80),
                        ('economy_confirmation', 0x4221a0)], budget_branch=0x268, budget_stack=0x78),
}

def collect(image, start):
    pending, found = [start], {}
    while pending:
        pc = pending.pop()
        if pc in found: continue
        if not start <= pc < start + 0x10000: raise ValueError('Unexpected branch')
        for i in md.disasm(bytes(image.data[pc:pc+0x4000]), pc):
            if i.address in found: break
            found[i.address] = i
            if i.group(CS_GRP_JUMP):
                assert i.operands[0].type == X86_OP_IMM
                pending.append(i.operands[0].imm)
                if i.mnemonic == 'jmp': break
            if i.mnemonic in ('ret', 'int3'): break
    return [i for _, i in sorted(found.items())]

def generate(layout):
    config = LAYOUTS[layout]
    functions, blocks = config['functions'], config['blocks']
    image = Image(ROOT / 'diagnostics/executables' / config['source'], config['mapped'])
    output = [f'// Generated by tools/generate_game_signatures.py from {config["source"]}.',
              '// All instruction bytes/field offsets and control-flow edges are checked.',
              '// Only PC-relative addresses vary. No disassembler is needed at runtime.']
    entries = {rva: n for n, (_, rva) in enumerate(functions + blocks)}
    symbols = {}
    for name, start in functions + blocks:
        block = (name, start) in blocks
        # Exclude the unrelated diagnostic error line after the economy access.
        end = start + 0x45 if name == 'economy_source' else None
        ins = image.ins(start, end) if block else collect(image, start)
        positions = {i.address: n for n, i in enumerate(ins)}
        output.append(f'static constexpr Instruction {name}_instructions[] = {{')
        for i in ins:
            code = bytearray(i.bytes)
            offset = width = kind = 0
            next_node = positions.get(i.address + i.size, -1)
            target = callee = symbol = -1
            if any(o.type == X86_OP_MEM and o.mem.base == X86_REG_RIP for o in i.operands):
                offset, width, kind = i.disp_offset, i.disp_size, 1
                destination = i.address + i.size + i.disp
                symbol = symbols.setdefault(destination, len(symbols))
            if (i.group(CS_GRP_CALL) or i.group(CS_GRP_JUMP)) and i.operands[0].type == X86_OP_IMM:
                offset, width, kind = i.imm_offset, i.imm_size, 2
                callee = entries.get(i.operands[0].imm, -1)
                if i.group(CS_GRP_JUMP) and i.operands[0].imm in positions:
                    kind = 3
                    target = positions[i.operands[0].imm]
                else:
                    symbol = symbols.setdefault(i.operands[0].imm, len(symbols))
                if i.mnemonic == 'jmp': next_node = -1
            if i.mnemonic in ('ret', 'int3'): next_node = -1
            if width: code[offset:offset+width] = bytes(width)
            values = ','.join(f'0x{b:02x}' for b in code)
            output.append(f'    {{{{{values}}}, {i.size},{offset},{width},{kind},{next_node},{target},{callee},{symbol}}},')
        output.append('};')
    output.append('static constexpr Signature signatures[] = {')
    for name, _ in functions + blocks:
        output.append(f'    {{"{name}", {name}_instructions, std::size({name}_instructions)}},')
    output += ['};', 'static constexpr unsigned economy_source_load = 0x20;',
               'static constexpr unsigned generator_clear_call = 0x34;',
               f'static constexpr unsigned generator_budget_branch = 0x{config["budget_branch"]:x};',
               f'static constexpr unsigned generator_budget_immediate = 0x{config["budget_branch"]+7:x};',
               f'static constexpr unsigned generator_budget_stack = 0x{config["budget_stack"]:x};']
    output.append(f'static constexpr unsigned symbol_count = {len(symbols)};')
    # Offsets are verified against actual decoded instructions before emission.
    generator = dict(functions)['generator']
    branch = generator + config['budget_branch']
    assert image.data[generator+0x34] == 0xe8
    assert image.data[branch:branch+2] == b'\x73\x0b'
    assert image.data[branch+2:branch+11] == b'\x48\xc7\x44\x24' + bytes([config['budget_stack'],4,0,0,0])
    return '\n'.join(output) + '\n'

def main(layouts=None):
    for layout in layouts or LAYOUTS:
        target = ROOT / f'src/game_signatures_{layout}.inc'
        result = generate(layout)
        if '--check' in sys.argv:
            assert target.read_text() == result, 'Generated signatures are stale'
        else:
            target.write_text(result)
        print(f'{target.name}: {len(result)} characters')

if __name__ == '__main__':
    main()
