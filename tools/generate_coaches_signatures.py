"""Emit checked Coaches instruction graphs from the local reference EXE.

Reference RVAs are build-time inputs only, never runtime compatibility gates.
External tail jumps remain linked references rather than being walked as blocks.
"""
import sys
from compare_executables import Image, ROOT, md, CS_GRP_JUMP, CS_GRP_CALL
from capstone.x86 import X86_OP_IMM, X86_OP_MEM, X86_REG_RIP

FUNCTIONS = [
    ('fill', 0x7bdb40), ('clear', 0x7be010), ('generate', 0x7be180),
    ('planner_init', 0x7be3d0), ('prepare', 0x7be6a0), ('commit', 0x7be900),
    ('append', 0x7bfbc0), ('validate', 0x7c01f0), ('factory', 0x7c0290),
    ('schedule', 0x809ef0), ('remove_events', 0x80a160),
    ('free_numbers', 0x10cf60), ('free_targets', 0x1ee360),
    ('clear_vector', 0x119ab0), ('stop_name', 0x7bd4b0),
]

EARLY_FUNCTIONS = list(zip([name for name,_ in FUNCTIONS],[
    0x7bd740,0x7bdc10,0x7bdd80,0x7bdfd0,0x7be2a0,0x7be500,
    0x7bf7b0,0x7bfde0,0x7bfe80,0x809ae0,0x809d50,
    0x10cf20,0x1ee320,0x119a70,0x7bd0b0,
]))

def collect(image, start, functions=FUNCTIONS):
    pending, found = [start], {}
    # Keep tail calls to other native entries external. Hot/cold fragments that
    # are not exported function entries remain part of this graph.
    roots = set(address for _, address in functions)
    while pending:
        pc = pending.pop()
        if pc in found: continue
        for ins in md.disasm(bytes(image.data[pc:pc+0x8000]), pc):
            if ins.address in found: break
            found[ins.address] = ins
            if ins.group(CS_GRP_JUMP):
                if ins.operands[0].type == X86_OP_IMM:
                    target = ins.operands[0].imm
                    if start <= target < start+0x10000 and (target == start or target not in roots):
                        pending.append(target)
                if ins.mnemonic == 'jmp': break
            if ins.mnemonic in ('ret', 'int3'): break
    return [ins for _, ins in sorted(found.items())]

def generate(early=False):
    snapshot='ets2-public-1.62.1.0' if early else 'ets2-public-1.62.3.3'
    image = Image(ROOT/'diagnostics/executables'/snapshot/'eurotrucks2.exe')
    functions=EARLY_FUNCTIONS if early else FUNCTIONS
    entries = {rva:n for n,(_,rva) in enumerate(functions)}
    symbols = {}
    output = ['// Generated by tools/generate_coaches_signatures.py.',
              '// Linked instruction/flow checks; resolve before any hooks.']
    for name, start in functions:
        assert start in image.functions, name
        code = collect(image,start,functions)
        positions = {ins.address:n for n,ins in enumerate(code)}
        assert code[0].address == start
        output.append(f'static constexpr Instruction {name}_instructions[] = {{')
        for ins in code:
            data = bytearray(ins.bytes)
            offset = width = kind = 0
            target = callee = symbol = -1
            next_node = positions.get(ins.address+ins.size,-1)
            if any(o.type==X86_OP_MEM and o.mem.base==X86_REG_RIP for o in ins.operands):
                offset,width,kind = ins.disp_offset,ins.disp_size,1
                symbol = symbols.setdefault(ins.address+ins.size+ins.disp,len(symbols))
            if (ins.group(CS_GRP_CALL) or ins.group(CS_GRP_JUMP)) and ins.operands[0].type==X86_OP_IMM:
                offset,width,kind = ins.imm_offset,ins.imm_size,2
                destination = ins.operands[0].imm
                callee = entries.get(destination,-1)
                if ins.group(CS_GRP_JUMP) and destination in positions:
                    kind,target = 3,positions[destination]
                else: symbol = symbols.setdefault(destination,len(symbols))
            if ins.mnemonic in ('jmp','ret','int3'): next_node=-1
            if width: data[offset:offset+width]=bytes(width)
            values=','.join(f'0x{b:02x}' for b in data)
            output.append(f'    {{{{{values}}}, {ins.size},{offset},{width},{kind},{next_node},{target},{callee},{symbol}}},')
        output.append('};')
    output.append('static constexpr Signature signatures[] = {')
    for name,_ in functions: output.append(f'    {{"{name}",{name}_instructions,std::size({name}_instructions)}},')
    output += ['};',f'static constexpr unsigned symbol_count={len(symbols)};']
    for n,(name,_) in enumerate(functions): output.append(f'static constexpr unsigned {name}_index={n};')
    return '\n'.join(output)+'\n'

if __name__=='__main__':
    for early in (False,True):
        path=ROOT/('src/coaches_signatures_162_early.inc' if early else 'src/coaches_signatures_162.inc')
        result=generate(early)
        if '--check' in sys.argv: assert path.read_text()==result, 'Coaches signatures are stale'
        else: path.write_text(result)
        print(f'{path.name}: {len(result)} characters')
